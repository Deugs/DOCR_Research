def fig_47_sympathetic_tripping_vectorized():
    data = _need(_CORE_J_CACHE, "J", 47, "sympathetic_tripping")
    sym = data.get("sympathetic")
    if sym is None or "sympathetic" not in sym or "traditional" not in sym:
        raise VectorizedDataMissingError(
            f"Fig 47 (sympathetic_tripping) requires a 'sympathetic' entry with sympathetic/traditional "
            f"counts in '{_CORE_J_CACHE}'.")
    marl_viol, trad_viol = int(sym["sympathetic"]), int(sym["traditional"])
    total = max(trad_viol, marl_viol, 1)
    prevented = max(total - marl_viol, 0)
    not_prevented = total - prevented

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    fig.suptitle("Figure 47 (vectorized) — Sympathetic Tripping Prevention Analysis", fontsize=13)

    ax = axes[0]
    labels = ["Prevented\n(vs. traditional)", "Remaining\nviolations"]
    wedges, texts, autotexts = ax.pie([prevented, not_prevented], labels=labels, colors=["#39d353", "#ff6b35"],
                                       autopct="%1.0f%%", startangle=90, textprops={"fontsize": 11, "fontweight": "bold"})
    for autotext in autotexts:
        autotext.set_color("white")
    ax.set_title(f"MARL: {marl_viol} violations vs. Traditional: {trad_viol}", fontsize=12)

    ax = axes[1]
    by_type = sym.get("by_fault_type") or {}
    fault_type_labels = {"1ph": "Line-to-Ground", "LL": "Line-to-Line", "3ph": "3-Phase"}
    scenarios, prevented_by_type, not_prevented_by_type = [], [], []
    for ft, label in fault_type_labels.items():
        if ft not in by_type:
            continue
        t = max(by_type[ft]["traditional"], by_type[ft]["marl"], 1)
        p = max(t - by_type[ft]["marl"], 0)
        scenarios.append(label); prevented_by_type.append(p); not_prevented_by_type.append(t - p)
    if scenarios:
        x = np.arange(len(scenarios)); width = 0.35
        ax.bar(x - width / 2, prevented_by_type, width, label="Prevented", color="#39d353", alpha=0.8, edgecolor="white")
        ax.bar(x + width / 2, not_prevented_by_type, width, label="Not Prevented", color="#ff6b35", alpha=0.8, edgecolor="white")
        ax.set_xticks(x); ax.set_xticklabels(scenarios, rotation=15, ha="right")
        ax.set_ylabel("Count", fontsize=11); ax.set_title("By Fault Type", fontsize=12)
        ax.legend(fontsize=10); ax.grid(True, alpha=0.3, axis="y")
    else:
        ax.axis("off")
        ax.text(0.5, 0.5, "No per-fault-type breakdown available", ha="center", va="center", fontsize=11)
    _save_fig_vectorized(fig, 47, "sympathetic_tripping")


