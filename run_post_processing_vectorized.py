def fig_05_objective_vs_pv_vectorized():
    data = _need(_CORE_B_CACHE, "B", 5, "objective_vs_pv")
    agg = {pv: [] for pv in _PV_LEVELS}
    for eval_run in data.get("task_evaluations", []):
        for pv, vals in eval_run.items():
            pv = float(pv) if isinstance(pv, str) else pv
            if pv in agg:
                agg[pv].append(vals.get("objective", 0))
    if not any(agg.values()):
        raise VectorizedDataMissingError(
            f"Fig 05 (objective_vs_pv) cache '{_CORE_B_CACHE}' has no usable task_evaluations entries.")
    means = [np.mean(agg[pv]) if agg[pv] else float("nan") for pv in _PV_LEVELS]
    stds = [np.std(agg[pv]) if agg[pv] else 0.0 for pv in _PV_LEVELS]

    fig, ax = plt.subplots(figsize=(10, 6))
    ax.errorbar(_PV_LEVELS, means, yerr=stds, fmt="o-", color="#2563eb", lw=2,
                markersize=10, capsize=5, label="MAPPO-Safe-EWC (vectorized)")
    ax.set_xlabel("PV Penetration", fontsize=12)
    ax.set_ylabel("Objective Function (s)", fontsize=12)
    ax.set_title("Figure 5 (vectorized) — Objective Function vs. PV Penetration (8-Bus)", fontsize=13)
    ax.set_xticks(_PV_LEVELS)
    ax.set_xticklabels([f"{int(p*100)}%" for p in _PV_LEVELS])
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=11)
    _save_fig_vectorized(fig, 5, "objective_vs_pv")


