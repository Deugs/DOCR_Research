    per_agent = data.get("per_agent_returns_mean")
    if per_agent is None or len(per_agent) == 0:
        raise VectorizedDataMissingError(
            f"Fig 37 (per_agent_curves) requires 'per_agent_returns_mean' in '{_CORE_A_CACHE}'.")
    n_agents = per_agent.shape[1] if per_agent.ndim > 1 else 1

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    fig.suptitle("Figure 37 (vectorized) — Per-Agent Learning Curves (Individual Convergence)", fontsize=13)

    ax = axes[0]
