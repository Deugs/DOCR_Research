#!/usr/bin/env python3
"""
run_post_processing_vectorized.py
----------------------------------
Plotting counterpart to run_core_training_vectorized.py -- part of the
GPU-vectorized-environment redesign (see .claude/plans/elegant-rolling-map.md,
Phases V14.1-V14.7, outside this repo). Mirrors how the real pipeline splits
run_core_training.py (train) from run_post_processing.py (plot): this script
generates publication-quality figures from the vectorized Cores A-K's own
cache output ONLY.

Hard rules, both enforced throughout this file:
  1. Reads ONLY from "_vectorized"-suffixed cache entries (e.g.
     "core_A_mappo_safe_ewc_8bus_60pv_vectorized") written by
     run_core_training_vectorized.py -- never the real, non-suffixed Core
     caches run_post_processing.py reads.
  2. NEVER fabricates data. If a required vectorized cache entry is missing
     or structurally unusable, the corresponding fig_NN_..._vectorized()
     function raises VectorizedDataMissingError naming the missing cache and
     the exact CLI command that would populate it -- it does not substitute
     placeholder/hardcoded numbers the way some of run_post_processing.py's
     real fig_NN_*() functions historically did (that file is being
     independently cleaned up of the same behavior; this script never had it
     to begin with).

Figures are saved under results/figures_vectorized/ (flat, NOT
results/figures/subdir/ -- this must never collide with or overwrite the
real thesis figures) as both .pdf and .png, same dual-format convention as
run_post_processing.py's save_fig().

Scope (confirmed by reading every real fig_NN_*() function in
run_post_processing.py and every orchestrator in
run_core_training_vectorized.py directly -- not assumed): 41 of the real
pipeline's 58 figures have a genuine vectorized-path cache counterpart.
Excluded:
  - figs 02, 03, 04, 34, 35, 52: pure hand-drawn schematics in the real
    pipeline too, no cache dependency of any kind.
  - figs 48, 49, 50 (SHAP / decision-boundary / critical-pairs): the real
    bridge-CLI-only eval methods behind these (_eval_shap/_eval_tsne/
    _eval_critical_pairs/_eval_action_space_grid) are never called by any
    real Core A-K and have zero vectorized counterpart anywhere in this
    redesign (Phase V14.7's own finding).
  - fig 19 (PV ride-through): generated by a standalone script
    (phase1_scripts/exp_fig19.py) in the real pipeline, not any Core cache
    at all -- same "out of scope" reasoning.

One real, pre-existing finding worth flagging explicitly (not fixed here,
since fixing it would mean diverging from run_core_training.py's own Core J
recipe, which this whole redesign's standing rule forbids modifying): Core
J's "coordination" field (Fig 43) is a fixed closed-form formula plus seeded
Gaussian jitter (`0.1 + 0.05*distance + noise`), not a measurement derived
from any actual relay rollout -- true in BOTH the real and vectorized Core J
recipes. It is treated here as "real" in the sense of "this is genuinely
what the vectorized Core J orchestrator computes and caches," matching the
real pipeline's own design, not as a claim that it reflects a physically
simulated coordination study.

One real, pre-existing finding this script does NOT reproduce despite the
real figure having it: the real fig_42_warm_start()'s "cold start" bars are
a hardcoded literal ([0.3, 0.35, 0.4, 0.45]) in the REAL function itself,
regardless of whether its cache is present -- a partial fabrication baked
into real pipeline. Since this script's whole purpose is "never fabricate,"
fig_42_warm_start_vectorized() below plots ONLY the real warm-start bars
(from core_B_curriculum_vectorized's genuine task_performances diagonal),
omitting the cold-start comparison entirely rather than inventing one.
"""

