def _core_b_task_perf_matrices(data: Dict, variant: str, fig_num: int, fig_name: str) -> np.ndarray:
    mats = [r["task_performances"] for r in data.get(variant, [])]
    if not mats:
        raise VectorizedDataMissingError(
            f"Fig {fig_num:02d} ({fig_name}) requires non-empty '{variant}' task_performances in "
            f"'{_CORE_B_CACHE}'.")
    return np.mean(mats, axis=0)


