def run_all_figures_vectorized() -> Dict[str, List[int]]:
    """Same per-figure try/except resilience pattern as run_post_processing.py's
    real run_all_figures(): one figure's VectorizedDataMissingError (or any
    other exception) is logged and does not abort the rest of the sweep."""
    completed, failed = [], []
    for fig_num in sorted(FIGURE_FUNCTIONS.keys()):
        try:
            t0 = time.time()
            FIGURE_FUNCTIONS[fig_num]()
            print(f"[Fig {fig_num:02d}] OK ({time.time() - t0:.1f}s)")
            completed.append(fig_num)
        except Exception as e:
            print(f"[Fig {fig_num:02d}] FAILED: {e}", file=sys.stderr)
            failed.append(fig_num)
    print(f"\nVectorized figures: {len(completed)} completed, {len(failed)} failed "
          f"(missing/unusable real cache data)."
          f"\nCompleted: {completed}\nFailed: {failed}")
    return {"completed": completed, "failed": failed}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--all", action="store_true", help="Generate all figures with real vectorized-cache data")
    parser.add_argument("--fig", type=int, nargs="+", help="Specific figure numbers")
    parser.add_argument("--list", action="store_true", help="List available vectorized figures")
    args = parser.parse_args()

    if args.list:
        print("\nAvailable vectorized figures (real data from run_core_training_vectorized.py only):")
        print("=" * 70)
        for fig_num in sorted(FIGURE_FUNCTIONS.keys()):
            print(f"  Fig {fig_num:<3} — {FIGURE_FUNCTIONS[fig_num].__name__}")
        print(f"\nTotal: {len(FIGURE_FUNCTIONS)} figures")
        print(f"Output directory: {FIGURES_DIR}")
        return

    if args.all:
        run_all_figures_vectorized()
    elif args.fig:
        for fig_num in args.fig:
            if fig_num not in FIGURE_FUNCTIONS:
                print(f"Figure {fig_num} not available in the vectorized pipeline.", file=sys.stderr)
                continue
            try:
                FIGURE_FUNCTIONS[fig_num]()
            except Exception as e:
                print(f"[Fig {fig_num:02d}] FAILED: {e}", file=sys.stderr)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
