    convergence_eps = []
    for i in range(n_agents):
        rewards = per_agent[:, i] if per_agent.ndim > 1 else per_agent
        final = rewards[-window:].mean() if len(rewards) > window else rewards.mean()
        target = 0.9 * final
        conv_ep = len(rewards)
        for ep in range(window, len(rewards)):
            if np.mean(rewards[ep - window:ep]) >= target:
                conv_ep = ep
                break
        convergence_eps.append(conv_ep)
    sorted_idx = np.argsort(convergence_eps)
    ax.barh(range(n_agents), [convergence_eps[i] for i in sorted_idx],
            color=[colors[i] for i in sorted_idx], edgecolor="white")
