def _ranked_methods(data: Dict) -> "tuple[list, dict]":
    methods = list(data.keys())
    final_perf = {m: np.mean(v[-100:] if hasattr(v, "__len__") and len(v) > 100 else v)
                  for m, v in data.items() if hasattr(v, "__len__") and len(v) > 0}
    sorted_methods = sorted(final_perf.keys(), key=lambda m: final_perf[m], reverse=True)
    return sorted_methods, {m: i + 1 for i, m in enumerate(sorted_methods)}


def _rank_diagram(data: Dict, fig_num: int, title: str, name: str):
    sorted_methods, ranks = _ranked_methods(data)
    n_methods = len(sorted_methods)
    if n_methods == 0:
        raise VectorizedDataMissingError(
            f"Fig {fig_num:02d} ({name}) requires at least one method with non-empty returns in "
            f"'{_CORE_C_CACHE}'.")
    fig, ax = plt.subplots(figsize=(12, 4))
    ax.set_xlim(0.5, n_methods + 0.5); ax.set_ylim(-0.5, 1.5)
    ax.axhline(0.5, color="black", lw=1)
    for i in range(1, n_methods + 1):
        ax.axvline(i, color="gray", alpha=0.3, ls="--")
        ax.text(i, 0.3, str(i), ha="center", fontsize=12, fontweight="bold")
    y_pos = 1.0
    for m in sorted_methods:
        ax.text(ranks[m], y_pos, m, ha="center", fontsize=10,
                bbox=dict(boxstyle="round,pad=0.3", facecolor="#2563eb" if "EWC" in m else "#f7c948", alpha=0.7))
        y_pos = 0.0 if y_pos == 1.0 else 1.0
    ax.set_title(title, fontsize=13); ax.axis("off")
    _save_fig_vectorized(fig, fig_num, name)


