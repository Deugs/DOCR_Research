class VectorizedDataMissingError(RuntimeError):
    """Raised by a fig_NN_..._vectorized() function when the real
    _vectorized cache(s) it needs are missing or structurally unusable.
    Never caught to substitute fabricated data -- only caught by
    run_all_figures_vectorized()'s per-figure try/except, which logs and
    continues to the next figure, same resilience pattern as the real
    pipeline's run_all_figures()."""


def _need(cache_name: str, core_letter: str, fig_num: int, fig_name: str) -> Dict:
    data = load_cache(cache_name)
    if data is None:
        raise VectorizedDataMissingError(
            f"Fig {fig_num:02d} ({fig_name}) requires real cache '{cache_name}' -- not found. "
            f"Run: python run_core_training_vectorized.py --core {core_letter}"
        )
    return data


def _need_multi(entries: "List[tuple[str, str]]", fig_num: int, fig_name: str) -> Dict[str, Dict]:
    """entries: list of (cache_name, core_letter). Raises ONE message naming
    every missing cache if any are absent, before any plotting work."""
    missing = []
    loaded = {}
    for name, letter in entries:
        d = load_cache(name)
        if d is None:
            missing.append((name, letter))
        else:
            loaded[name] = d
    if missing:
        detail = "; ".join(f"'{n}' (run --core {l})" for n, l in missing)
        raise VectorizedDataMissingError(
            f"Fig {fig_num:02d} ({fig_name}) requires real cache(s) not found: {detail}"
        )
    return loaded


def _save_fig_vectorized(fig, fig_num: int, name: str, dpi: int = 200) -> None:
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    base = FIGURES_DIR / f"fig_{fig_num:02d}_{name}_vectorized"
    for ext in (".pdf", ".png"):
        fig.savefig(base.with_suffix(ext), dpi=dpi, bbox_inches="tight")
    plt.close(fig)
    print(f"[Fig {fig_num:02d}] Saved: {base}.pdf / {base}.png")


